/*输入一个以#结束的字符串，本题要求将小写字母全部转换成大写字母，把大写字母全部转换成小写字母，其它字符不变。
输入格式：
输入在一行中给出一个长度不超过40的、以#结束的非空字符串。
输出格式：
在一行中按照要求输出转换后的字符串。*/
#include <stdio.h>
int main()
{
	char c;
	
	while(1){//将字符理解为数，小写=大写+32
		scanf("%c",&c);
		if(c=='#'){
			break;
		}
		if(c>='a'&&c<='z'){
			c=c-32;
		}
		else if(c>='A'&&c<='Z'){
			c=c+32;
		}
			printf("%c",c);
	}
	
	return 0;
}